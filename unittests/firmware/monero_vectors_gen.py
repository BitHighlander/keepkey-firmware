#!/usr/bin/env python3
"""Write the Monero Core fixtures as a C header for firmware-unit.

Input: the public reference cases in
tools/monero-feasibility/evidence/2026-11-04-interoperability/host.json,
generated by tools/monero-feasibility/reference.py from pinned Monero Core
arithmetic and the published fixture mnemonics. No wallet secrets.
"""
import argparse
import json

FIELDS = ["key_seed", "spend_secret", "view_secret", "tx_public",
          "output_public", "output_secret", "key_image"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    reference = json.load(open(args.input))
    reference = reference.get("reference", reference)
    cases = reference["cases"]
    if len(cases) != reference["case_count"] or not cases:
        raise SystemExit("reference case count mismatch")
    lines = ["/* Generated by monero_vectors_gen.py from Monero Core fixtures. */",
             "#ifndef MONERO_CORE_VECTORS_H", "#define MONERO_CORE_VECTORS_H",
             "#include <stdint.h>",
             "typedef struct {", "  const char* label;",
             "  uint32_t major, minor, output_index;"]
    lines += ["  uint8_t %s[32];" % f for f in FIELDS]
    lines += ["  const char* address;", "} MoneroCoreCase;",
              "static const MoneroCoreCase monero_core_cases[] = {"]
    for case in cases:
        values = ", ".join(
            "{%s}" % ", ".join("0x%s" % case[f][i:i + 2] for i in range(0, 64, 2))
            for f in FIELDS)
        lines.append('  {"%s", %du, %du, %du, %s, "%s"},' % (
            case["label"], case["major"], case["minor"], case["output_index"],
            values, case["address"]))
    lines += ["};", "#define MONERO_CORE_CASE_COUNT %du" % len(cases), "#endif", ""]
    open(args.output, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
