RESOURCES = {None: 0, "BANDWIDTH": 0, "ENERGY": 1, "TRON_POWER": 2}


def fetch():
    vectors = []
    for name, txid in TXIDS:
        request = urllib.request.Request(
            API, data=json.dumps({"value": txid}).encode(),
            headers={"Content-Type": "application/json"})
        tx = json.load(urllib.request.urlopen(request, timeout=60))
        assert tx["txID"] == txid and tx["ret"][0]["contractRet"] == "SUCCESS"
        vectors.append({
            "name": name,
            "_source": "POST %s {\"value\": \"%s\"}" % (API, txid),
            "txID": txid,
            "raw_data_hex": tx["raw_data_hex"],
            "raw_data": tx["raw_data"],
            "ret": tx["ret"],
        })
    with open(JSON_PATH, "w") as f:
        json.dump({"_comment": __doc__.strip(), "vectors": vectors}, f,
                  indent=1, sort_keys=True)
        f.write("\n")


def cstr(text):
    return '"%s"' % text


def header():
    with open(JSON_PATH) as f:
        vectors = json.load(f)["vectors"]
    rows = []
    for v in vectors:
        raw = bytes.fromhex(v["raw_data_hex"])
        assert hashlib.sha256(raw).hexdigest() == v["txID"], v["name"]
        (contract,) = v["raw_data"]["contract"]
        value = contract["parameter"]["value"]
        data = value.get("data", "")
        votes = ", ".join("{%s, %dULL}" % (cstr(x["vote_address"]), x["vote_count"])
                          for x in value.get("votes", []))
        rows.append("  {%s, %s, %s, %s, %s, %s, %s, %s, %dULL, %d, %s, {%s}}," % (
            cstr(v["name"]), cstr(v["txID"]), cstr(v["raw_data_hex"]),
            cstr(contract["type"]),
            "true" if "Permission_id" in contract else "false",
            cstr(value["owner_address"]), cstr(value.get("contract_address", "")),
            cstr(data),
            value.get("frozen_balance", value.get("unfreeze_balance", 0)),
            RESOURCES[value.get("resource")],
            "true" if "fee_limit" in v["raw_data"] else "false",
            votes))
    with open(HEADER_PATH, "w") as f:
        f.write("// Generated by scripts/tron_vectors.py from tron_vectors.json: real\n"
                "// TRON mainnet transactions (TronGrid), expected values from TronGrid's\n"
                "// own decode. Do not edit by hand.\n"
                "#include <cstdint>\n#include <string>\n#include <vector>\n"
                "namespace tronv {\n"
                "struct Vote { std::string address; uint64_t count; };\n"
                "struct Vec {\n"
                "  std::string name, txid, raw_hex, type;\n"
                "  bool permission_id;\n"
                "  std::string owner, contract, data;\n"
                "  uint64_t stake_amount;\n"
                "  int resource;\n"
                "  bool fee_limit;\n"
                "  std::vector<Vote> votes;\n"
                "};\n"
                "inline const std::vector<Vec>& all() { static const std::vector<Vec> v = {\n")
        f.write("\n".join(rows))
        f.write("\n}; return v; }\n}  // namespace tronv\n")


if __name__ == "__main__":
    if sys.argv[1:] == ["fetch"]:
        fetch()
    header()
