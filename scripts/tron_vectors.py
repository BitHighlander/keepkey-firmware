#!/usr/bin/env python3

"""Real TRON mainnet transactions for unittests/firmware/tron.cpp.

  tron_vectors.py fetch   # TronGrid -> unittests/firmware/tron_vectors.json
  tron_vectors.py         # tron_vectors.json -> unittests/firmware/tron_vectors.h

Each vector keeps TronGrid's own decode of the transaction (raw_data), so the
expected values in the header come from TronGrid, not from the firmware
parser. The header step checks sha256(raw_data_hex) == txID: the bytes are the
ones the chain accepted.
"""

